import { z } from "zod";

export const VideoSchema = z.object({
  videoId: z.string(),
  title: z.string(),
  channel: z.string(),
  link: z.string(),
  published: z.string(),
  isShort: z.boolean(),
  thumbnailUrl: z.string().optional(),
  viewCount: z.number().optional(),
  likeCount: z.number().optional(),
  description: z.string().optional(),
});

export const SubscriptionSchema = z.object({
  channelId: z.string(),
  title: z.string(),
});

export const IdsResponseSchema = z.object({
  ids: z.array(z.string()),
});

export const SubtitleCueSchema = z.object({
  start: z.number(),
  end: z.number(),
  text: z.string(),
});

export const SubtitlesSchema = z.object({
  videoId: z.string(),
  language: z.string(),
  isAutoGenerated: z.boolean(),
  cues: z.array(SubtitleCueSchema),
});

export type VideoDto = z.infer<typeof VideoSchema>;
export type SubscriptionDto = z.infer<typeof SubscriptionSchema>;
export type IdsResponse = z.infer<typeof IdsResponseSchema>;
export type SubtitleCueDto = z.infer<typeof SubtitleCueSchema>;
export type SubtitlesDto = z.infer<typeof SubtitlesSchema>;
