import {
  BadGatewayException,
  HttpException,
  HttpStatus,
  Injectable,
  Logger,
  NotFoundException,
} from '@nestjs/common';
import { execFile } from 'node:child_process';
import { mkdtemp, readFile, readdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { promisify } from 'node:util';
import type { SubtitlesDto } from '@subs/contracts';
import { parseRollingVtt, parseVtt } from './vtt.js';

const execFileAsync = promisify(execFile);

const YTDLP_TIMEOUT_MS = 60_000;
const YTDLP_MAX_BUFFER = 20 * 1024 * 1024;

export type ExecYtDlp = (
  args: string[],
) => Promise<{ stdout: string; stderr: string }>;

const defaultExecYtDlp: ExecYtDlp = (args) =>
  execFileAsync(process.env.YTDLP_PATH ?? 'yt-dlp', args, {
    timeout: YTDLP_TIMEOUT_MS,
    maxBuffer: YTDLP_MAX_BUFFER,
  });

interface ExecError extends Error {
  code?: string | number;
  stderr?: string;
  killed?: boolean;
}

function isExecError(error: unknown): error is ExecError {
  return error instanceof Error;
}

@Injectable()
export class SubtitlesService {
  private readonly logger = new Logger(SubtitlesService.name);

  execYtDlp: ExecYtDlp = defaultExecYtDlp;

  async getSubtitles(videoId: string, lang: string): Promise<SubtitlesDto> {
    const dir = await mkdtemp(join(tmpdir(), 'subs-'));
    try {
      const stdout = await this.download(videoId, lang, dir);
      const file = (await readdir(dir)).find((name) =>
        name.endsWith(`.${lang}.vtt`),
      );
      if (!file) {
        throw new NotFoundException(
          `No '${lang}' subtitles available for video ${videoId}`,
        );
      }

      const vtt = await readFile(join(dir, file), 'utf8');
      const isAutoGenerated = !this.hasManualSubtitles(stdout, lang);
      const cues = isAutoGenerated ? parseRollingVtt(vtt) : parseVtt(vtt);

      return { videoId, language: lang, isAutoGenerated, cues };
    } finally {
      await rm(dir, { recursive: true, force: true });
    }
  }

  private async download(
    videoId: string,
    lang: string,
    dir: string,
  ): Promise<string> {
    const args = [
      '--skip-download',
      '--no-simulate',
      '--write-subs',
      '--write-auto-subs',
      '--sub-langs',
      lang,
      '--sub-format',
      'vtt',
      '--no-playlist',
      '--no-warnings',
      '--quiet',
      '--print',
      '%(subtitles)j',
      '--paths',
      dir,
      '--output',
      '%(id)s.%(ext)s',
      '--',
      videoId,
    ];

    try {
      const { stdout } = await this.execYtDlp(args);
      return stdout;
    } catch (error) {
      if (!isExecError(error)) throw error;

      const stderr = error.stderr ?? '';
      if (
        /video unavailable|this video is unavailable|private video/i.test(
          stderr,
        )
      ) {
        throw new NotFoundException(`Video ${videoId} not found`);
      }

      if (/HTTP Error 429/.test(stderr)) {
        throw new HttpException(
          'Rate limited by YouTube, try again later',
          HttpStatus.TOO_MANY_REQUESTS,
        );
      }

      this.logger.error(
        `yt-dlp failed for ${videoId} (${error.code ?? 'unknown'}${error.killed ? ', timed out' : ''}): ${stderr.trim() || error.message}`,
      );
      throw new BadGatewayException('Failed to fetch subtitles from YouTube');
    }
  }

  private hasManualSubtitles(stdout: string, lang: string): boolean {
    try {
      const subtitles = JSON.parse(stdout.trim()) as Record<
        string,
        unknown
      > | null;
      return subtitles !== null && Object.hasOwn(subtitles, lang);
    } catch {
      return false;
    }
  }
}
