import { describe, test, expect, mock } from 'bun:test';
import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import {
  BadGatewayException,
  HttpException,
  NotFoundException,
} from '@nestjs/common';
import { SubtitlesService, type ExecYtDlp } from '../subtitles.service.js';

const VTT = `WEBVTT

00:00:01.000 --> 00:00:02.000
hello

00:00:02.000 --> 00:00:03.000
hello
world
`;

function argAfter(args: string[], flag: string): string {
  return args[args.indexOf(flag) + 1];
}

function fakeYtDlp(options: {
  subtitles: Record<string, unknown>;
  writeLang?: string;
}): ExecYtDlp {
  return mock(async (args: string[]) => {
    if (options.writeLang) {
      const dir = argAfter(args, '--paths');
      await writeFile(join(dir, `vid.${options.writeLang}.vtt`), VTT);
    }
    return { stdout: JSON.stringify(options.subtitles) + '\n', stderr: '' };
  });
}

function failingYtDlp(stderr: string): ExecYtDlp {
  return mock(() =>
    Promise.reject(
      Object.assign(new Error('Command failed'), { code: 1, stderr }),
    ),
  );
}

function createService(execYtDlp: ExecYtDlp): SubtitlesService {
  const service = new SubtitlesService();
  service.execYtDlp = execYtDlp;
  return service;
}

describe('SubtitlesService', () => {
  test('returns manual subtitles without rolling dedupe', async () => {
    const service = createService(
      fakeYtDlp({ subtitles: { en: [] }, writeLang: 'en' }),
    );

    const result = await service.getSubtitles('dQw4w9WgXcQ', 'en');

    expect(result).toEqual({
      videoId: 'dQw4w9WgXcQ',
      language: 'en',
      isAutoGenerated: false,
      cues: [
        { start: 1, end: 2, text: 'hello' },
        { start: 2, end: 3, text: 'hello\nworld' },
      ],
    });
  });

  test('flags auto-generated subtitles and dedupes rolling lines', async () => {
    const service = createService(
      fakeYtDlp({ subtitles: { de: [] }, writeLang: 'en' }),
    );

    const result = await service.getSubtitles('dQw4w9WgXcQ', 'en');

    expect(result.isAutoGenerated).toBe(true);
    expect(result.cues).toEqual([
      { start: 1, end: 2, text: 'hello' },
      { start: 2, end: 3, text: 'world' },
    ]);
  });

  test('passes the video id after an end-of-options marker', async () => {
    const exec = fakeYtDlp({ subtitles: {}, writeLang: 'en' });
    await createService(exec).getSubtitles('dQw4w9WgXcQ', 'en');

    const args = (exec as ReturnType<typeof mock>).mock.calls[0][0] as string[];
    expect(args.slice(-2)).toEqual(['--', 'dQw4w9WgXcQ']);
    expect(argAfter(args, '--sub-langs')).toBe('en');
  });

  test('throws 404 when no subtitle file is written', async () => {
    const service = createService(fakeYtDlp({ subtitles: {} }));
    const error = await service
      .getSubtitles('dQw4w9WgXcQ', 'fr')
      .catch((e: unknown) => e);
    expect(error).toBeInstanceOf(NotFoundException);
  });

  test('throws 404 when the video is unavailable', async () => {
    const service = createService(
      failingYtDlp('ERROR: [youtube] x: This video is unavailable'),
    );
    const error = await service
      .getSubtitles('dQw4w9WgXcQ', 'en')
      .catch((e: unknown) => e);
    expect(error).toBeInstanceOf(NotFoundException);
  });

  test('throws 429 when YouTube rate limits', async () => {
    const service = createService(
      failingYtDlp(
        "ERROR: Unable to download video subtitles for 'af': HTTP Error 429: Too Many Requests",
      ),
    );
    const error = await service
      .getSubtitles('dQw4w9WgXcQ', 'af')
      .catch((e: unknown) => e);
    expect(error).toBeInstanceOf(HttpException);
    expect((error as HttpException).getStatus()).toBe(429);
  });

  test('throws 502 on other yt-dlp failures', async () => {
    const service = createService(failingYtDlp('ERROR: something broke'));
    const error = await service
      .getSubtitles('dQw4w9WgXcQ', 'en')
      .catch((e: unknown) => e);
    expect(error).toBeInstanceOf(BadGatewayException);
  });
});
